/**
 * Provides Large Language Model (LLM) integration for the documentation pipeline.
 *
 * <p>
 * This package contains the service layer responsible for routing documentation content
 * creation requests to an appropriate chat model. It abstracts model selection from the
 * rest of the document pipeline by resolving a model based on the content creation
 * stereotype and executing the prompt against the selected LLM.
 * </p>
 *
 * <p>
 * The central entry point is {@link de.spraener.prjxp.docpipe.llm.LLMService}. It accepts
 * a {@link de.spraener.prjxp.docpipe.content.ContentCreationTask}, extracts the associated
 * {@link de.spraener.prjxp.docpipe.model.DPContentCreation}, and uses its stereotype to
 * locate a suitable chat implementation via
 * {@link de.spraener.prjxp.common.chat.KIChatProvider}. Before invocation, the selected
 * chat model is decorated by {@link de.spraener.prjxp.common.mcp.McpClientManager}, allowing
 * MCP-related capabilities or context to be applied consistently.
 * </p>
 *
 * <p>
 * Primary use cases include:
 * </p>
 * <ul>
 *   <li>Sending prompts generated by documentation pipeline tasks to an LLM.</li>
 *   <li>Resolving LLM configurations indirectly through content stereotypes.</li>
 *   <li>Keeping model selection and MCP decoration concerns outside the content creation workflow.</li>
 * </ul>
 *
 * <p>
 * If no model is configured for a requested stereotype, the service fails fast with an
 * {@link java.lang.IllegalArgumentException}, making configuration errors explicit to callers
 * and maintainers.
 * </p>
 */
package de.spraener.prjxp.docpipe.llm;

